async def seed_locations() -> None:
    """Insert seed locations if the table is empty. Safe to call on every startup."""
    async with AsyncSessionLocal() as session:
        result = await session.execute(select(Location).limit(1))
        existing = result.scalars().first()
        if existing:
            return  # Already seeded

        for data in SEED_LOCATIONS:
            session.add(Location(**data))

        await session.commit()
